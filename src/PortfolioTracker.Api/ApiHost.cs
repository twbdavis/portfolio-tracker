using System.Reflection;
using Microsoft.AspNetCore.Builder;
using Microsoft.AspNetCore.Hosting;
using Microsoft.AspNetCore.Hosting.Server;
using Microsoft.AspNetCore.Http;
using Microsoft.AspNetCore.Hosting.Server.Features;
using Microsoft.Extensions.DependencyInjection;
using Microsoft.Extensions.FileProviders;
using Microsoft.Extensions.Hosting;
using Microsoft.Extensions.Logging;
using PortfolioTracker.Api.Endpoints;
using PortfolioTracker.Api.Hubs;
using PortfolioTracker.Api.Services;

namespace PortfolioTracker.Api;

public class ApiHostOptions
{
    public required string AppDataDir { get; init; }
    /// Per-session bearer token generated by the shell; required on every /api
    /// call and the SignalR connection so other local processes can't drive us.
    public required string Token { get; init; }
    /// Dev only: a Vite origin (e.g. http://localhost:5173) allowed via CORS.
    public string? DevCorsOrigin { get; init; }
}

/// The in-process local server: Kestrel on 127.0.0.1 with a random free port,
/// embedded React static files, JSON endpoints over Core, and the SignalR hub.
public class ApiHost : IAsyncDisposable
{
    private WebApplication? _app;
    public Uri BaseUri { get; private set; } = null!;
    public CoreServices Core { get; private set; } = null!;
    public AlertEvents Alerts { get; private set; } = null!;

    public async Task StartAsync(ApiHostOptions options)
    {
        var builder = WebApplication.CreateBuilder();
        builder.Logging.ClearProviders();
        builder.Logging.AddDebug();
        builder.WebHost.UseUrls("http://127.0.0.1:0");   // random free port, loopback only

        Core = CoreServices.Create(options.AppDataDir);
        Alerts = new AlertEvents();
        builder.Services.AddSingleton(Core);
        builder.Services.AddSingleton(Alerts);
        builder.Services.AddSingleton(options);
        builder.Services.AddSingleton<Endpoints.ImportSessions>();
        builder.Services.AddSingleton<QuotePoller>();
        builder.Services.AddHostedService(sp => sp.GetRequiredService<QuotePoller>());
        builder.Services.AddSingleton<UniverseCrawler>();
        builder.Services.AddHostedService(sp => sp.GetRequiredService<UniverseCrawler>());
        builder.Services.AddSingleton<SignalService>();
        builder.Services.ConfigureHttpJsonOptions(o =>
            o.SerializerOptions.Converters.Add(new System.Text.Json.Serialization.JsonStringEnumConverter()));
        builder.Services.AddSignalR().AddJsonProtocol(o =>
            o.PayloadSerializerOptions.Converters.Add(new System.Text.Json.Serialization.JsonStringEnumConverter()));
        if (options.DevCorsOrigin is not null)
            builder.Services.AddCors(o => o.AddDefaultPolicy(p => p
                .WithOrigins(options.DevCorsOrigin).AllowAnyHeader().AllowAnyMethod().AllowCredentials()));

        _app = builder.Build();
        if (options.DevCorsOrigin is not null) _app.UseCors();
        _app.UseMiddleware<TokenAuthMiddleware>();

        var embedded = new ManifestEmbeddedFileProvider(Assembly.GetExecutingAssembly(), "wwwroot");
        _app.UseDefaultFiles(new DefaultFilesOptions { FileProvider = embedded });
        _app.UseStaticFiles(new StaticFileOptions { FileProvider = embedded });

        _app.MapPortfolioEndpoints();
        _app.MapHub<PortfolioHub>("/hub");
        // SPA fallback: client-side routes resolve to the React entry point
        _app.MapFallback(async ctx =>
        {
            ctx.Response.ContentType = "text/html";
            await ctx.Response.SendFileAsync(embedded.GetFileInfo("index.html"));
        });

        await _app.StartAsync();
        var address = _app.Services.GetRequiredService<IServer>()
            .Features.Get<IServerAddressesFeature>()!.Addresses.First();
        BaseUri = new Uri(address);
    }

    public async ValueTask DisposeAsync()
    {
        if (_app is not null) await _app.DisposeAsync();
    }
}

/// Rejects /api and /hub requests without the session token. Static files are
/// exempt — they are the app shell itself and carry no data.
public class TokenAuthMiddleware(RequestDelegate next, ApiHostOptions options)
{
    public async Task InvokeAsync(HttpContext ctx)
    {
        var path = ctx.Request.Path;
        if (path.StartsWithSegments("/api") || path.StartsWithSegments("/hub"))
        {
            var header = ctx.Request.Headers.Authorization.ToString();
            var token = header.StartsWith("Bearer ", StringComparison.Ordinal)
                ? header["Bearer ".Length..]
                : ctx.Request.Query["access_token"].ToString();   // SignalR WebSocket path
            if (token != options.Token)
            {
                ctx.Response.StatusCode = StatusCodes.Status401Unauthorized;
                return;
            }
        }
        await next(ctx);
    }
}
